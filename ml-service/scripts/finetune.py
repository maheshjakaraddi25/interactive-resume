"""
GPT-2 Fine-Tuning with LoRA
─────────────────────────────
Base model : GPT-2 small (124M parameters, 12 layers, 12 heads, 768 hidden dim)
Method     : LoRA via HuggingFace PEFT
Dataset    : data/training_data.jsonl (generated by generate_training_data.py)
Output     : models/gpt2-mahesh-lora/

WHY GPT-2 and not a modern model (Llama, Mistral)?
  GPT-2 small (124M params) fine-tunes on CPU in ~15-20 min.
  Llama 3.1 8B needs at least 16GB GPU RAM, even with QLoRA.
  For a portfolio demo without a GPU: GPT-2 is the honest choice.
  The TECHNIQUES (LoRA, tokenization, training loop) are identical
  regardless of model size — that's what matters for skill demonstration.

WHY LoRA over full fine-tuning?
  Full fine-tuning GPT-2 small is actually feasible (124M params fits in RAM).
  BUT LoRA is the industry standard for fine-tuning ANY model, including the
  large ones you'll encounter in production. Demonstrating LoRA on GPT-2
  shows you understand the technique, not just that you have a big GPU.

LoRA mechanics:
  For each attention weight matrix W (shape d×d):
  Instead of updating W directly, learn:
    ΔW = A × B   where A is (d×r) and B is (r×d), rank r << d
  W_new = W_frozen + α/r × A × B

  GPT-2 small attention: W is 768×768 = 589,824 parameters
  LoRA rank=8: A is 768×8, B is 8×768 = 12,288 parameters
  Reduction: 589,824 → 12,288 = 48× fewer params per matrix

  With rank=8, lora_alpha=32, applied to c_attn (combined QKV projection):
  Total trainable params: ~294,912 (0.24% of GPT-2's 124M)

Run: python scripts/finetune.py
"""

import sys, os
sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))

import json
import torch
from torch.utils.data import Dataset, DataLoader
from transformers import GPT2LMHeadModel, GPT2Tokenizer, get_linear_schedule_with_warmup
from peft import LoraConfig, get_peft_model, TaskType

DATA_FILE  = os.path.join(os.path.dirname(__file__), "../data/training_data.jsonl")
MODEL_DIR  = os.path.join(os.path.dirname(__file__), "../models/gpt2-mahesh-lora")

# ── Hyperparameters ────────────────────────────────────────────────────────────
MAX_LENGTH    = 512     # GPT-2's context window is 1024 — we use 512 for speed
BATCH_SIZE    = 4       # small batch for CPU training
EPOCHS        = 3
LEARNING_RATE = 2e-4    # higher LR works with LoRA since few params are trainable
WARMUP_STEPS  = 50

# ── LoRA config ────────────────────────────────────────────────────────────────
LORA_R      = 8    # rank — higher = more capacity but more params
LORA_ALPHA  = 32   # scaling factor: effective_lr = lr * alpha/r = lr * 4
LORA_TARGET = ["c_attn"]  # GPT-2's combined QKV attention projection

# ── Dataset ────────────────────────────────────────────────────────────────────

class ResumeQADataset(Dataset):
    """
    Format: "<question> ### <answer> <|endoftext|>"
    GPT-2 is trained to predict the full sequence.
    At inference, we provide the question prefix and let GPT-2 complete it.
    """

    def __init__(self, jsonl_path: str, tokenizer: GPT2Tokenizer, max_length: int):
        self.samples = []
        with open(jsonl_path, "r") as f:
            for line in f:
                item = json.loads(line.strip())
                text = f"{item['prompt']} ### {item['completion']}{tokenizer.eos_token}"
                encoded = tokenizer(
                    text,
                    truncation=True,
                    max_length=max_length,
                    padding="max_length",
                    return_tensors="pt",
                )
                input_ids = encoded["input_ids"].squeeze()
                # Labels = input_ids for causal LM (predict next token)
                # Mask padding tokens with -100 so loss ignores them
                labels = input_ids.clone()
                labels[labels == tokenizer.pad_token_id] = -100
                self.samples.append((input_ids, labels))

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        return self.samples[idx]


# ── Training ───────────────────────────────────────────────────────────────────

def finetune():
    if not os.path.exists(DATA_FILE):
        print(f"ERROR: Training data not found at {DATA_FILE}")
        print("Run: python scripts/generate_training_data.py first")
        sys.exit(1)

    print("\n[finetune] Loading GPT-2 small tokenizer and model...")
    tokenizer = GPT2Tokenizer.from_pretrained("gpt2")
    tokenizer.pad_token = tokenizer.eos_token  # GPT-2 has no pad token by default

    base_model = GPT2LMHeadModel.from_pretrained("gpt2")

    # ── Apply LoRA ─────────────────────────────────────────────────────────────
    lora_config = LoraConfig(
        task_type=TaskType.CAUSAL_LM,
        r=LORA_R,
        lora_alpha=LORA_ALPHA,
        target_modules=LORA_TARGET,
        lora_dropout=0.1,
        bias="none",
    )
    model = get_peft_model(base_model, lora_config)

    trainable, total = model.get_nb_trainable_parameters()
    print(f"[finetune] Total parameters    : {total:,}")
    print(f"[finetune] Trainable (LoRA)    : {trainable:,}")
    print(f"[finetune] Trainable %         : {100 * trainable / total:.2f}%")
    print(f"[finetune] LoRA rank           : {LORA_R}")
    print(f"[finetune] LoRA alpha          : {LORA_ALPHA}")
    print(f"[finetune] Target modules      : {LORA_TARGET}")

    # ── Dataset ────────────────────────────────────────────────────────────────
    print(f"\n[finetune] Loading training data from {DATA_FILE}...")
    dataset    = ResumeQADataset(DATA_FILE, tokenizer, MAX_LENGTH)
    dataloader = DataLoader(dataset, batch_size=BATCH_SIZE, shuffle=True)
    print(f"[finetune] Training samples: {len(dataset)}")

    # ── Optimizer + Scheduler ──────────────────────────────────────────────────
    optimizer = torch.optim.AdamW(model.parameters(), lr=LEARNING_RATE)
    total_steps = len(dataloader) * EPOCHS
    scheduler = get_linear_schedule_with_warmup(
        optimizer,
        num_warmup_steps=WARMUP_STEPS,
        num_training_steps=total_steps,
    )

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[finetune] Training on: {device}")
    model.to(device)
    model.train()

    # ── Training loop ──────────────────────────────────────────────────────────
    print(f"\n[finetune] Starting training — {EPOCHS} epochs, {len(dataloader)} steps/epoch\n")

    for epoch in range(EPOCHS):
        total_loss = 0.0
        for step, (input_ids, labels) in enumerate(dataloader):
            input_ids = input_ids.to(device)
            labels    = labels.to(device)

            outputs = model(input_ids=input_ids, labels=labels)
            loss    = outputs.loss

            optimizer.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            scheduler.step()

            total_loss += loss.item()

            if (step + 1) % 10 == 0:
                avg = total_loss / (step + 1)
                print(f"  Epoch {epoch+1}/{EPOCHS}  Step {step+1}/{len(dataloader)}  Loss: {avg:.4f}")

        avg_epoch_loss = total_loss / len(dataloader)
        print(f"\n[finetune] Epoch {epoch+1} complete — avg loss: {avg_epoch_loss:.4f}\n")

    # ── Save ───────────────────────────────────────────────────────────────────
    os.makedirs(MODEL_DIR, exist_ok=True)
    model.save_pretrained(MODEL_DIR)
    tokenizer.save_pretrained(MODEL_DIR)

    # Save training metadata
    meta = {
        "base_model":        "gpt2",
        "method":            "LoRA",
        "lora_r":            LORA_R,
        "lora_alpha":        LORA_ALPHA,
        "target_modules":    LORA_TARGET,
        "trainable_params":  trainable,
        "total_params":      total,
        "trainable_pct":     round(100 * trainable / total, 2),
        "epochs":            EPOCHS,
        "training_samples":  len(dataset),
        "max_length":        MAX_LENGTH,
        "device":            str(device),
    }
    with open(os.path.join(MODEL_DIR, "training_meta.json"), "w") as f:
        json.dump(meta, f, indent=2)

    print(f"[finetune] Model saved to {MODEL_DIR}")
    print(f"[finetune] Start the ML service to serve this model: uvicorn main:app --reload\n")


if __name__ == "__main__":
    finetune()
